# OPERACIONES CON LISTAS
#
# | Operación   | Qué hace                              | Ejemplo                 |
# |-------------|---------------------------------------|-------------------------|
# | .append(x)  | Añade x al final                      | frutas.append("limón")  |
# | .insert(i,x)| Inserta x en la posición i             | frutas.insert(0,"mango")|
# | .remove(x)  | Quita la primera x que encuentre       | frutas.remove("pera")  |
# | .pop()      | Saca y devuelve el último elemento     | frutas.pop()            |
# | len(lista)  | Dice cuántos elementos hay             | len(frutas) → 4         |
# | x in lista  | Comprueba si x está en la lista        | "kiwi" in frutas → True |
# | .sort()     | Ordena la lista                        | numeros.sort()          |