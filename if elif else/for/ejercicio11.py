# Ejercicios cortos de bucles. (a) muestra los numeros del 1 al 10 con for, (b) muestra los numeros del 1 al 10 con while

# (a) muestra los numeros del 1 al 10 con for
for i in range(1, 11):
    print(i)

# (b) muestra los numeros del 1 al 10 con while
numero = 1
while numero <= 10:
    print(numero)
    numero += 1